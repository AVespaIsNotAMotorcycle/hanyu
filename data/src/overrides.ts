/** An entry's key in these tables. */
export const overrideKey = (hskId: number, simplified: string) =>
  `${String(hskId).padStart(5, '0')} ${simplified}`;

/** Throws unless every override names a real word, so a typo can't do nothing. */
export function checkOverrides(
  words: readonly { hskId: number; simplified: string }[],
): void {
  const keys = new Set(words.map((w) => overrideKey(w.hskId, w.simplified)));
  for (const key of [...Object.keys(TRADITIONAL), ...Object.keys(GLOSSES)]) {
    if (!keys.has(key)) throw new Error(`Override for unknown word: ${key}`);
  }
}
